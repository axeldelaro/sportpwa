const FOOD_MAP = new Map(
  FOOD_DATABASE.map((f) => [f.id, { ...f, sourceRef: f.sourceRef || 'ANSES CIQUAL / USDA' }])
);
const EXTERNAL_FOOD_LIST = [];

export function registerExternalFoods(foods = []) {
  const list = Array.isArray(foods) ? foods : [foods];
  for (const f of list) {
    if (!f?.id || !f?.per100g) continue;
    FOOD_MAP.set(f.id, f);
    const existingIdx = EXTERNAL_FOOD_LIST.findIndex((x) => x.id === f.id);
    if (existingIdx >= 0) {
      EXTERNAL_FOOD_LIST[existingIdx] = f;
    } else {
      EXTERNAL_FOOD_LIST.push(f);
    }
  }
}

export function getAllFoods() {
  return [...FOOD_DATABASE, ...EXTERNAL_FOOD_LIST];
}

export function getFoodById(foodId) {
  return FOOD_MAP.get(foodId) || null;
}

export function calculateFoodMacros(foodOrId, grams = 100) {
  const food = typeof foodOrId === 'string' ? getFoodById(foodOrId) : foodOrId;
  if (!food) {
    return { kcal: 0, protein: 0, carbs: 0, fat: 0, fiber: 0 };
  }
  const ratio = Math.max(0, Number(grams) || 0) / 100;
  return {
    kcal: Math.round(food.per100g.kcal * ratio),
    protein: Math.round(food.per100g.protein * ratio * 10) / 10,
    carbs: Math.round(food.per100g.carbs * ratio * 10) / 10,
    fat: Math.round(food.per100g.fat * ratio * 10) / 10,
    fiber: Math.round((food.per100g.fiber || 0) * ratio * 10) / 10,
  };
}

export function isFoodDislikedByProfile(foodOrId, profile) {
  if (!profile || !Array.isArray(profile.dislikedFoodIds)) return false;
  const id = typeof foodOrId === 'string' ? foodOrId : foodOrId?.id;
  return Boolean(id && profile.dislikedFoodIds.includes(id));
}

export function isFoodCompatibleWithProfile(food, profile, options = {}) {
  if (!food) return false;
  if (!profile) return true;

  if (
    !options.ignoreDislikes &&
    Array.isArray(profile.dislikedFoodIds) &&
    profile.dislikedFoodIds.includes(food.id)
  ) {
    return false;
  }

  const tags = food.tags || [];
  const dietBase = profile.dietBase || 'omnivore';
  const restrictions = profile.restrictions || [];

  if (dietBase === 'vegetarien') {
    if (
      tags.includes('viande') ||
      tags.includes('porc') ||
      tags.includes('poisson') ||
      tags.includes('crustace')
    ) {
      return false;
    }
  }

  if (dietBase === 'vegan') {
    if (
      tags.includes('viande') ||
      tags.includes('porc') ||
      tags.includes('poisson') ||
      tags.includes('crustace') ||
      tags.includes('oeuf') ||
      tags.includes('produit_laitier') ||
      tags.includes('miel')
    ) {
      return false;
    }
  }

  if (restrictions.includes('sans_lactose') && tags.includes('lactose')) return false;
  if (restrictions.includes('sans_gluten') && tags.includes('gluten')) return false;
  if (restrictions.includes('sans_oeufs') && tags.includes('oeuf')) return false;
  if (restrictions.includes('sans_fruits_a_coque') && tags.includes('fruits_a_coque')) return false;
  if (restrictions.includes('sans_porc') && tags.includes('porc')) return false;
  if (
    restrictions.includes('sans_poissons_crustaces') &&
    (tags.includes('poisson') || tags.includes('crustace'))
  ) {
    return false;
  }
  if (restrictions.includes('digestion_sensible') && tags.includes('alliaces_fodmap')) {
    return false;
  }

  return true;
}
